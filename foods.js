const FOODS = FOOD_RAW.trim().split("\n").map(line => {
  const [name, cat, kcal, p, c, f, units] = line.split("|");
  return {
    name, cat,
    kcal: +kcal, p: +p, c: +c, f: +f,
    units: units ? units.split(",").filter(Boolean).map(s => {
      const [unit, g] = s.split(":");
      return { unit, g: +g };
    }) : [],
    alias: [],
  };
});

const BY_NAME = {};
FOODS.forEach(f => { BY_NAME[f.name] = f; });

ALIAS_RAW.trim().split("\n").forEach(line => {
  const [k, vs] = line.split("|");
  if (BY_NAME[k]) BY_NAME[k].alias = vs.split(",");
});

function findFood(q) {
  const key = (q || "").trim().toLowerCase();
  if (!key) return [];
  const scored = [];
  for (const f of FOODS) {
    let best = 0;
    for (const n of [f.name.toLowerCase(), ...f.alias.map(a => a.toLowerCase())]) {
      if (n === key) best = Math.max(best, 100);
      else if (n.includes(key) || key.includes(n)) best = Math.max(best, 80 - Math.abs(n.length - key.length) * 3);
    }
    if (best) scored.push([f, best]);
  }
  scored.sort((a, b) => b[1] - a[1] || a[0].name.localeCompare(b[0].name, "zh"));
  return scored.map(x => x[0]);
}
